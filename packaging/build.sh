#!/bin/bash
# build.sh: build and check the packages for one distribution.
# SPDX-License-Identifier: GPL-3.0-or-later
#
# Usage: packaging/build.sh fedora|ubuntu|arch
#
# Run as root from the top of a checkout, in a fresh container of that
# distribution (Fedora 45, Ubuntu 26.04 or Arch Linux): it installs the build
# tools, builds the packages from a source archive of the checkout (and, for
# Fedora and Ubuntu, an archive of the crates, so the build itself runs
# offline), writes them to build/packages/<distribution>/, then checks them:
# no file is in two packages, the core package installs and runs, with its
# commands executable and its systemd user unit in place, every package's
# dependencies resolve, and the desktop packages hold their parts and reach
# the core.
set -euo pipefail

distro=${1:?usage: packaging/build.sh fedora|ubuntu|arch}
version=$(sed -nE 's/^ *"version": "([^"]+)".*/\1/p' manifest.json)
top=$PWD
out=$top/build/packages/$distro
work=$top/build/work-$distro
core=/usr/share/megacmd-applet
unit=/usr/lib/systemd/user/mega-cmd-server.service

# Writes a source archive of the checkout, as megacmd-applet-VERSION/, to $1.
source_archive() {
    tar --exclude=./.git --exclude=./build --exclude=./cosmic/target --exclude=./crates \
        --exclude=__pycache__ --transform "s,^\.,megacmd-applet-$version," -czf "$1" .
}

# Makes the archive of the crates with make crates and copies it to $1.
crates_archive() {
    make crates
    cp "build/megacmd-applet-crates-$version.tar.gz" "$1"
}

# Checks the installed core: it prints the view of a saved state, its
# commands are executable and the engine's user unit is installed.
check_core() {
    local home missing
    home=$(mktemp -d)
    HOME=$home $core/bin/megacmd-applet status \
        --fixture $core/fixtures/sync-error.json --home /home/user --fresh |
        python3 -c 'import json, sys; view = json.load(sys.stdin); assert view["kind"] == "error", view'
    missing=$(find $core/bin -type f ! -name '*.sh' ! -perm -u+x)
    [ -z "$missing" ] || { echo "not executable: $missing" >&2; exit 1; }
    grep -qx 'ExecStart=mega-cmd-server' $unit
    grep -qx 'WantedBy=default.target' $unit
    echo "core: runs, commands executable, user unit in place"
}

# Checks that no file is in two of the packages unpacked in the folders $@.
check_overlap() {
    local twice
    twice=$(for root in "$@"; do (cd "$root" && find . ! -type d); done | sort | uniq -d)
    [ -z "$twice" ] || { echo "in more than one package: $twice" >&2; exit 1; }
    echo "packages: no file in two"
}

# Checks the desktop packages' files, unpacked under $1: each part is there
# and the KDE and GNOME parts link to the installed core, by an absolute or
# a relative link.
check_parts() {
    local root=$1 link target desktop
    for link in usr/share/plasma/plasmoids/io.github.yardquit.megacmd/contents/megacmd \
                usr/share/gnome-shell/extensions/megacmd@yardquit.github.io/megacmd; do
        target=$(readlink "$root/$link")
        case $target in
            /*) ;;
            *) target=$(realpath -m "/$(dirname "$link")/$target") ;;
        esac
        [ "$target" = "$core" ] || { echo "$link does not link to $core" >&2; exit 1; }
    done
    test -f "$root/usr/share/plasma/plasmoids/io.github.yardquit.megacmd/metadata.json"
    test -f "$root/usr/share/gnome-shell/extensions/megacmd@yardquit.github.io/schemas/gschemas.compiled"
    test -x "$root/usr/bin/cosmic-applet-megacmd"
    desktop=$root/usr/share/applications/io.github.yardquit.MegaCmd.desktop
    grep -q '^Exec=/usr/bin/cosmic-applet-megacmd' "$desktop"
    echo "desktop parts: in place"
}

# Checks the crates' licence file $1: it names the lock file and holds
# libcosmic's licence.
check_licences() {
    grep -q "^Generated by scripts/third-party-licences.py from cosmic/Cargo.lock" "$1"
    grep -q "^Mozilla Public License Version 2.0" "$1"
    echo "crate licences: in place"
}

# Unpacks each package file after $1 into its own folder under $work/files,
# for check_overlap, and into $work/parts together, for check_parts, with the
# command $1, which takes a package file and a folder.
unpack_all() {
    local unpack=$1 package
    shift
    mkdir -p "$work/files" "$work/parts"
    for package in "$@"; do
        mkdir -p "$work/files/${package##*/}"
        "$unpack" "$package" "$work/files/${package##*/}"
        "$unpack" "$package" "$work/parts"
    done
    check_overlap "$work"/files/*
}

unpack_rpm() { rpm2cpio "$1" | (cd "$2" && cpio -idm --quiet); }
unpack_deb() { dpkg-deb -x "$1" "$2"; }
unpack_arch() { bsdtar -xf "$1" -C "$2" --exclude '.*'; }

build_fedora() {
    local packages resolved
    dnf -y -q install rpm-build dnf-plugins-core cpio tar
    dnf -y -q builddep packaging/fedora/megacmd-applet.spec
    mkdir -p "$work"/{SOURCES,RPMS,SRPMS,BUILD,SPECS}
    source_archive "$work/SOURCES/megacmd-applet-$version.tar.gz"
    crates_archive "$work/SOURCES/megacmd-applet-crates-$version.tar.gz"
    rpmbuild -ba --define "_topdir $work" packaging/fedora/megacmd-applet.spec
    # The debug packages are checked but not published.
    packages=("$work"/RPMS/*/*.rpm)
    cp "$work"/SRPMS/*.rpm "$out/"
    for rpm in "${packages[@]}"; do
        case $rpm in
            *-debuginfo-* | *-debugsource-*) ;;
            *) cp "$rpm" "$out/" ;;
        esac
    done
    unpack_all unpack_rpm "${packages[@]}"
    dnf -y -q install "$out"/megacmd-applet-"$version"-*.x86_64.rpm
    check_core
    # dnf only resolves the transaction here; it prints a summary when every
    # dependency is found.
    resolved=$(dnf install --assumeno "${packages[@]}" 2>&1 || true)
    grep -q '^Transaction Summary' <<<"$resolved" || { echo "$resolved" >&2; exit 1; }
    echo "dependencies: resolve"
    check_parts "$work/parts"
    check_licences "$work/parts/usr/share/licenses/megacmd-applet-cosmic/THIRD-PARTY-LICENCES"
}

build_ubuntu() {
    local tree=$work/megacmd-applet-$version
    export DEBIAN_FRONTEND=noninteractive
    apt-get update -qq
    apt-get install -y -qq build-essential dpkg-dev debhelper >/dev/null
    mkdir -p "$work"
    source_archive "$work/megacmd-applet_$version.orig.tar.gz"
    tar -xzf "$work/megacmd-applet_$version.orig.tar.gz" -C "$work"
    cp -r packaging/debian "$tree/debian"
    (cd "$tree" && apt-get build-dep -y -qq ./ >/dev/null)
    crates_archive "$work/megacmd-applet_$version.orig-crates.tar.gz"
    tar -xzf "$work/megacmd-applet_$version.orig-crates.tar.gz" -C "$tree"
    (cd "$tree" && dpkg-buildpackage -us -uc -b)
    cp "$work"/*.deb "$out/"
    unpack_all unpack_deb "$out"/*.deb
    apt-get install -y -qq "$out"/megacmd-applet_"$version"-*_all.deb >/dev/null
    check_core
    apt-get install -s -qq "$out"/*.deb >/dev/null
    echo "dependencies: resolve"
    check_parts "$work/parts"
    check_licences "$work/parts/usr/share/doc/megacmd-applet-cosmic/THIRD-PARTY-LICENCES"
}

build_arch() {
    pacman -Syu --noconfirm --needed base-devel >/dev/null
    # makepkg refuses to run as root.
    id builder >/dev/null 2>&1 || useradd -m builder
    mkdir -p "$work"
    cp packaging/arch/PKGBUILD packaging/arch/*.install "$work/"
    source_archive "$work/megacmd-applet-$version.tar.gz"
    # shellcheck disable=SC1091,SC2046
    pacman -S --noconfirm --needed $(source "$work/PKGBUILD" && echo "${makedepends[@]}" "${checkdepends[@]}") >/dev/null
    chown -R builder "$work"
    (cd "$work" && runuser -u builder -- makepkg --noconfirm)
    cp "$work"/*.pkg.tar.zst "$out/"
    unpack_all unpack_arch "$out"/*.pkg.tar.zst
    pacman -U --noconfirm "$out"/megacmd-applet-"$version"-*-any.pkg.tar.zst >/dev/null
    check_core
    pacman -U --print --noconfirm "$out"/*.pkg.tar.zst >/dev/null
    echo "dependencies: resolve"
    check_parts "$work/parts"
    check_licences "$work/parts/usr/share/licenses/megacmd-applet-cosmic/THIRD-PARTY-LICENCES"
    test -f "$work/parts/usr/share/megacmd-applet/manifest.json"
    echo "omarchy plugin: in place"
}

rm -rf "$out" "$work"
mkdir -p "$out"
case $distro in
    fedora | ubuntu | arch) "build_$distro" ;;
    *) echo "usage: packaging/build.sh fedora|ubuntu|arch" >&2; exit 2 ;;
esac
ls -l "$out"
